export const messages: Record<SupportedLocale, MessageDictionary> = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

export function getMessages(locale: SupportedLocale): MessageDictionary {
  return messages[locale];
}

export function messageKeys(): string[] {
  return Object.keys(zhCN).sort();
}

export function translate(
  locale: SupportedLocale,
  key: string,
  values?: Record<string, string | number>,
): string {
  const template = messages[locale][key] ?? messages["zh-CN"][key];
  if (!template) {
    if (process.env.NODE_ENV !== "test" && typeof console !== "undefined") {
      console.warn(`[i18n] Missing message key: ${key}`);
    }
    return key;
  }
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values?.[name] ?? `{${name}}`));
}

export function localizedQualificationText(
  value: string,
  t: (key: string, values?: Record<string, string | number>) => string,
): string {
  if (value === "长期有效") return t("qualifications.status.longTerm");
  if (value === "有效") return t("qualifications.status.valid");
  if (value === "今日到期") return t("qualifications.status.today");
  const expired = value.match(/已(?:过期|逾期)\s*(\d+)\s*天?/);
  if (expired) {
    return t("qualifications.status.expired", { days: Number(expired[1]) });
  }
  const remaining = value.match(/剩余\s*(\d+)\s*天/);
  if (remaining) return t("qualifications.status.remaining", { days: Number(remaining[1]) });
  return value;
}
